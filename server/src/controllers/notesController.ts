// @desc    AI enhance note (Legacy endpoint, wraps enhanceNotes helper)
// @route   POST /api/notes/:id/enhance
// @access  Protected
export const enhanceNote = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const note = await Notes.findOne({ _id: req.params.id, user: req.user!._id });
    if (!note) {
      res.status(404).json({ message: 'Note not found' });
      return;
    }
    const rawAnalysis = await analyzeNoteContent(note.title, note.content);
    let analysis: any;
    try {
      const cleaned = rawAnalysis.replace(/```json|```/gi, '').trim();
      analysis = JSON.parse(cleaned);
    } catch {
      res.status(500).json({ message: 'Failed to enhance note' });
      return;
    }
    note.summary = analysis.summary;
    note.aiSummary = analysis.summary;
    note.tags = analysis.tags || [];
    note.category = analysis.category || 'General Tech';
    await note.save();
    res.json({ success: true, note });
  } catch (error) {
    console.error('Enhance note failed:', error);
    res.status(500).json({ message: 'Failed to enhance note' });
  }
};
