import { Response } from 'express';
import { AuthRequest } from '../middleware/authMiddleware';
import Notes from '../models/Notes';
import { analyzeNoteContent } from '../services/aiService';

// @desc    Create new note with AI analysis and validation
// @route   POST /api/notes
// @access  Protected
export const createNote = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { title, content } = req.body;
    if (!title || !title.trim() || !content || !content.trim()) {
      res.status(400).json({ message: 'Title and content cannot be empty' });
      return;
    }

    // Call AI analyzer to validate and enrich the note
    const rawAnalysis = await analyzeNoteContent(title, content);
    let analysis: any;
    try {
      const cleaned = rawAnalysis.replace(/```json|```/gi, '').trim();
      analysis = JSON.parse(cleaned);
    } catch {
      // Fallback if JSON parsing fails
      analysis = {
        isTechRelated: true,
        summary: 'Summary generated by CareerGPT AI.',
        tags: ['Tech'],
        category: 'General Tech'
      };
    }

    if (!analysis.isTechRelated) {
      res.status(400).json({ message: 'This Learning Hub supports ONLY tech-related notes.' });
      return;
    }

    const note = await Notes.create({
      user: req.user!._id,
      title: title.trim(),
      content: content.trim(),
      summary: analysis.summary,
      aiSummary: analysis.summary,
      tags: analysis.tags || [],
      category: analysis.category || 'General Tech'
    });

    res.status(201).json({ success: true, note });
  } catch (error) {
    console.error('Create note failed:', error);
    res.status(500).json({ message: 'Server error' });
  }
};

// @desc    Get all notes (with search + category filter)
// @route   GET /api/notes
// @access  Protected
export const getNotes = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { search, category } = req.query;
    const query: any = { user: req.user!._id };
    if (search) {
      query.$text = { $search: search as string };
    }
    if (category) {
      query.category = category;
    }
    const notes = await Notes.find(query).sort({ updatedAt: -1 });
    res.json({ success: true, notes });
  } catch (error) {
    console.error('Get notes failed:', error);
    res.status(500).json({ message: 'Server error' });
  }
};

