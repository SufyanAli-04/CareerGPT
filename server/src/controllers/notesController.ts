// @desc    Update note with AI re-analysis on modification
// @route   PUT /api/notes/:id
// @access  Protected
export const updateNote = async (req: AuthRequest, res: Response): Promise<void> => {
  try {
    const { title, content, tags, category } = req.body;
    const noteId = req.params.id;

    const note = await Notes.findOne({ _id: noteId, user: req.user!._id });
    if (!note) {
      res.status(404).json({ message: 'Note not found' });
      return;
    }

    let updatedFields: any = { ...req.body };

    // If title or content changed, re-validate and update summary/tags/category automatically
    if ((title && title.trim() !== note.title) || (content && content.trim() !== note.content)) {
      const finalTitle = title ? title.trim() : note.title;
      const finalContent = content ? content.trim() : note.content;

      if (!finalTitle || !finalContent) {
        res.status(400).json({ message: 'Title and content cannot be empty' });
        return;
      }

      const rawAnalysis = await analyzeNoteContent(finalTitle, finalContent);
      let analysis: any;
      try {
        const cleaned = rawAnalysis.replace(/```json|```/gi, '').trim();
        analysis = JSON.parse(cleaned);
      } catch {
        analysis = {
          isTechRelated: true,
          summary: note.summary || note.aiSummary,
          tags: note.tags,
          category: note.category
        };
      }

      if (!analysis.isTechRelated) {
        res.status(400).json({ message: 'This Learning Hub supports ONLY tech-related notes.' });
        return;
      }

      updatedFields.summary = analysis.summary;
      updatedFields.aiSummary = analysis.summary;
      updatedFields.tags = analysis.tags || [];
      updatedFields.category = analysis.category || 'General Tech';
    }

    const updatedNote = await Notes.findOneAndUpdate(
      { _id: noteId, user: req.user!._id },
      { ...updatedFields },
      { new: true }
    );

    res.json({ success: true, note: updatedNote });
  } catch (error) {
    console.error('Update note failed:', error);
    res.status(500).json({ message: 'Server error' });
  }
};

